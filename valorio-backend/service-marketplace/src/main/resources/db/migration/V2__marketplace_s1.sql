CREATE TABLE marketplace_item (
    id BIGSERIAL PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    description TEXT NOT NULL,
    category VARCHAR(50) NOT NULL,
    item_condition VARCHAR(50) NOT NULL,
    item_type VARCHAR(50) NOT NULL,
    status VARCHAR(50) NOT NULL DEFAULT 'AVAILABLE',
    price NUMERIC(10, 2) NOT NULL DEFAULT 0,
    ai_estimated_price NUMERIC(10, 2),
    ai_price_fairness VARCHAR(50),
    ai_verification_score DOUBLE PRECISION,
    ai_moderation_notes VARCHAR(500),
    original_object_id VARCHAR(100),
    location VARCHAR(200),
    seller_id BIGINT,
    seller_name VARCHAR(150),
    seller_email VARCHAR(150),
    seller_phone VARCHAR(50),
    image_url VARCHAR(1000),
    tags VARCHAR(500),
    unclaimed_days INT DEFAULT 90,
    views_count INT DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE marketplace_offer (
    id BIGSERIAL PRIMARY KEY,
    item_id BIGINT NOT NULL REFERENCES marketplace_item (id) ON DELETE CASCADE,
    buyer_name VARCHAR(150) NOT NULL,
    buyer_email VARCHAR(150) NOT NULL,
    buyer_phone VARCHAR(50),
    offered_price NUMERIC(10, 2),
    message TEXT,
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

